import {renderHook, cleanup} from "@testing-library/react";
import {afterEach, expect, it, vi} from "vitest";
import {MemoryRouter} from "react-router";
import type {ReactNode} from "react";
import {HRContext, type HRContextValue} from "../src/house-context";
import {useLocalInfiniteList, useLocalList, useLocalShow} from "../src/hooks/use-local-data";
const fallback = vi.hoisted(() => ({list: vi.fn(), infinite: vi.fn(), show: vi.fn()}));
vi.mock("@refinedev/core", () => ({useList: fallback.list, useInfiniteList: fallback.infinite, useShow: fallback.show}));
const data = {teams: [], employees: [{id: "e", firstName: "Ada"}], "time-offs": [{id: "pending", employeeId: "e", status: "Pending", createdAt: "2026-10-11"}, {id: "approved", employeeId: "e", status: "Approved", createdAt: "2026-10-10"}]};
const wrapper = ({children}: {children: ReactNode}) => <MemoryRouter><HRContext.Provider value={{database: data} as unknown as HRContextValue}>{children}</HRContext.Provider></MemoryRouter>;
afterEach(cleanup);
it("renders list, complete local pagination and record detail immediately without starting a Refine fetch", () => {
  fallback.list.mockReturnValue({query: {isLoading: true}, result: undefined});
  fallback.infinite.mockReturnValue({query: {isLoading: true}, result: {data: undefined}});
  fallback.show.mockReturnValue({query: {isLoading: true}});
  const list = renderHook(() => useLocalList({resource: "time-offs", pagination: {pageSize: 1}, filters: [{field: "status", operator: "eq", value: "Pending"}]}), {wrapper});
  expect(list.result.current.result).toMatchObject({total: 1, data: [{id: "pending"}]});
  expect(list.result.current.query.isLoading).toBe(false);
  expect(fallback.list.mock.calls[0][0].queryOptions.enabled).toBe(false);
  const infinite = renderHook(() => useLocalInfiniteList({resource: "time-offs", meta: {join: ["employee"]}}), {wrapper});
  expect(infinite.result.current.result.data?.pages[0].data).toHaveLength(2);
  expect(infinite.result.current.result.hasNextPage).toBe(false);
  expect(infinite.result.current.query.isLoading).toBe(false);
  expect(fallback.infinite.mock.calls[0][0].queryOptions.enabled).toBe(false);
  const detail = renderHook(() => useLocalShow({resource: "time-offs", id: "pending", meta: {join: ["employee"]}}), {wrapper});
  expect(detail.result.current.query.data?.data).toMatchObject({id: "pending", employee: {firstName: "Ada"}});
  expect(detail.result.current.query.isLoading).toBe(false);
  expect(fallback.show.mock.calls[0][0].queryOptions.enabled).toBe(false);
});
